#!/usr/bin/env python3
"""Estimate the dollar cost of the recorded runs from the token usage stored in runs/*/attempt_N.json.

No model calls. runs/ is local and not committed, so this runs only where runs/ exists; docs/COST.md is the committed output.
Two scenarios because the pricing page does not say how reasoning tokens are billed:
  A: every completion token, reasoning included, at the output rate
  B: reasoning tokens not billed
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RATES = {  # USD per 1M tokens: (cached input, input, output); Standard mode; https://dev.meta.ai/docs/pricing-rate-limits
    "muse-spark-1.3": (0.15, 1.25, 4.25),
    "muse-wonder-1.0": (0.20, 4.00, 20.00),
    "muse-glimmer": (0.0, 0.0, 0.0),  # runs locally: no API cost; electricity is not counted
}


def attempt_cost(path):
    d = json.load(open(path))
    cached_rate, in_rate, out_rate = RATES[d["model"]]
    u = d.get("usage") or {}
    a = b = tokens = 0.0
    for c in u.get("per_call", [u]):
        prompt = c.get("prompt_tokens", 0)
        cached = (c.get("prompt_tokens_details") or {}).get("cached_tokens", 0)
        completion = c.get("completion_tokens", 0)
        reasoning = (c.get("completion_tokens_details") or {}).get("reasoning_tokens", 0)
        base = cached * cached_rate + (prompt - cached) * in_rate
        a += (base + completion * out_rate) / 1e6
        b += (base + (completion - reasoning) * out_rate) / 1e6
        tokens += prompt + completion
    return a, b, tokens


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--billed", type=float, help="USD spent according to the Billing page (read by hand)")
    ap.add_argument("--billed-at", default="", help="when the Billing page was read, for example '2026-10-28 22:10 local time'")
    args = ap.parse_args()
    rows = ["| result file | model | mode | runs | solved | tokens | USD A | USD B |", "|---|---|---|---|---|---|---|---|"]
    tot_a = tot_b = tot_t = 0.0
    for f in sorted((ROOT / "results").glob("bench_*.json")):
        data = json.load(open(f))
        a = b = t = 0.0
        runs = solved = 0
        for row in data:
            runs += row["runs"]
            solved += row["successes"]
            for r in row["results"]:
                if not r.get("run_dir"):
                    continue
                for p in sorted((ROOT / r["run_dir"]).glob("attempt_*.json")):
                    x, y, z = attempt_cost(p)
                    a += x
                    b += y
                    t += z
        mode = "tools" if (data[0].get("config") or {}).get("tools") else "one-shot"
        rows.append(f"| `{f.name}` | {data[0].get('model')} | {mode} | {runs} | {solved} | {int(t)} | {a:.2f} | {b:.2f} |")
        tot_a += a
        tot_b += b
        tot_t += t
    all_a = all_b = all_t = 0.0
    n_attempts = 0
    for p in sorted((ROOT / "runs").glob("*/attempt_*.json")):
        try:
            x, y, z = attempt_cost(p)
        except KeyError:
            continue
        all_a += x
        all_b += y
        all_t += z
        n_attempts += 1
    note = ["# Estimated cost of the recorded runs", "",
            "Generated by `scripts/cost_estimate.py` from the token usage stored with each attempt. Rates: Standard mode, "
            "https://dev.meta.ai/docs/pricing-rate-limits (read on 2026-10-28). The page does not say how reasoning tokens are "
            "billed, so there are two scenarios: A = every completion token (reasoning included) at the output rate, B = reasoning "
            "tokens not billed. Cached input tokens are priced at the cached rate where the response reported them. These are "
            "estimates, not invoices.", ""] + rows + ["",
            f"Sum over the result files above: {tot_t:.0f} tokens, USD {tot_a:.2f} (A) / {tot_b:.2f} (B).",
            f"Sum over every attempt file found in runs/ ({n_attempts} attempts, includes runs that are in no result file): "
            f"{all_t:.0f} tokens, USD {all_a:.2f} (A) / {all_b:.2f} (B)."]
    if args.billed is not None:
        note.append(f"Spend shown on the Billing page: USD {args.billed:.2f}" + (f" (read {args.billed_at})" if args.billed_at else "") + ".")
    note += ["", "Not covered: the ping and tool probe calls, and any request that failed before an attempt file was written."]
    text = "\n".join(note) + "\n"
    (ROOT / "docs" / "COST.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
