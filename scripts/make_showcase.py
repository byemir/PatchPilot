#!/usr/bin/env python3
"""Build docs/RESULTS.md and examples/ from results/*.json and runs/. No model calls; standard library only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
PICKS = [  # (folder, result file, case, run number inside that file)
    ("n6-wonder-first-try", "bench_20261028-174452_muse-wonder-1.0.json", "n6_uint8_scaling", 1),
    ("n7-spark-two-attempts", "bench_20261028-180119_muse-spark-1.3.json", "n7_float32_scalars", 4),
    ("p1-wonder-two-attempts", "bench_20261028-174452_muse-wonder-1.0.json", "p1_epoch_seconds", 1),
    ("p2-wonder-two-attempts", "bench_20261028-174452_muse-wonder-1.0.json", "p2_dst_day_offset", 3),
    ("p3-spark-two-attempts", "bench_20261028-102955_muse-spark-1.3.json", "p3_groupby_report", 2),
    ("p4-wonder-one-shot-first-try", "bench_20261027-225746_muse-wonder-1.0.json", "p4_label_histogram", 3),
    ("p4-wonder-differential-recovery-before-layer", "bench_20261027-191341_muse-wonder-1.0.json", "p4_label_histogram", 3),
    ("p4-wonder-tools-two-attempts", "bench_20261028-095554_muse-wonder-1.0_tools.json", "p4_label_histogram", 2),
    ("p4-spark-gate-off-accepted-but-diverges", "bench_20261027-204730_muse-spark-1.3.json", "p4_label_histogram", 2),
    ("n6-glimmer-local-first-try", "bench_20261028-210347_muse-glimmer_local.json", "n6_uint8_scaling", 1),
    ("n7-glimmer-local-three-attempts", "bench_20261028-210626_muse-glimmer_local.json", "n7_float32_scalars", 2),
]


def gate(d):
    if "error" in d:
        return "invalid reply"
    if not (d.get("old_verdict") == "OK" and d.get("new_verdict") == "OK"):
        return "rejected at visible check"
    if not (d.get("hidden_old") == "OK" and d.get("hidden_new") == "OK"):
        return "rejected at hidden check"
    if (d.get("differential") or {}).get("verdict") not in (None, "PASS", "WEAK"):
        return "rejected at differential"
    return "accepted"


def short(x, n):
    t = x if isinstance(x, str) else json.dumps(x)
    t = " ".join(t.split())
    return t if len(t) <= n else t[:n] + "..."


def layer(row):
    c = row.get("config") or {}
    if "fs_deny" not in c:
        return "before the isolation layer"
    return "isolation layer on, counted" if c["fs_deny"] and row.get("counted") else "isolation layer OFF, not counted"


def mode(row):
    c = row.get("config") or {}
    return ("tools" if c.get("tools") else "one-shot") + (" (local endpoint)" if c.get("endpoint") else "")


def gate_setting(row):
    c = row.get("config")
    if not c or "diff_check" not in c:
        return "not recorded"
    return "differential gate on" if c["diff_check"] else "differential gate off"


# ---- docs/RESULTS.md
L = ["# Recorded results", "",
     "Generated by `scripts/make_showcase.py` from `results/bench_*.json`; nothing here is typed by hand. All cases are synthetic, "
     "samples are small (1 to 5 runs per case and file), only token counts were recorded (no dollar cost). Files from before the "
     "isolation layer ran model code without the OS layer and with the API key in the process environment. "
     "See the README for the setup, the limits and the engineering log for caveats.", "",
     "| file | model | effort | mode | layer | gate | case | runs | solved | first try | re-scored pass | avg tokens |",
     "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for f in sorted(RES.glob("bench_*.json")):
    for row in json.load(open(f)):
        L.append(f"| `{f.name}` | {row.get('model')} | {row.get('effort')} | {mode(row)} | {layer(row)} | {gate_setting(row)} | "
                 f"{row['case']} | {row['runs']} | {row['successes']} | {row['first_try']} | {row.get('scored_pass', '-')} | {row['avg_tokens']} |")
Path(ROOT / "docs" / "RESULTS.md").write_text("\n".join(L) + "\n")

# ---- examples/
ex = ROOT / "examples"
ex.mkdir(exist_ok=True)
index = ["# Example patches", "",
         "Patches produced by the models in recorded runs, chosen to show the cases and the gates (not a random sample); `results/` has the matching rows. Each folder has `patch.diff` (the accepted "
         "patch), `attempts.md` (gate outcome per attempt, the model's own diagnosis, the differential counterexample where there was "
         "one) and `meta.json`. Accepted means: passed the gates that were on in that run. It does not mean the patch is correct beyond "
         "those checks. The folder `p4-spark-gate-off-accepted-but-diverges` shows a patch accepted without the differential gate that "
         "failed the differential check afterwards. Generated by `scripts/make_showcase.py`.", "",
         "| folder | case | model | mode | layer | attempts | tokens | gate per attempt | re-scored |", "|---|---|---|---|---|---|---|---|---|"]
for slug, fname, case, n in PICKS:
    row = next(r for r in json.load(open(RES / fname)) if r["case"] == case)
    r = row["results"][n - 1]
    assert r.get("success") and r.get("run_dir"), f"{slug}: run {n} of {fname} is not a successful run"
    run = ROOT / r["run_dir"]
    attempts = [json.load(open(p)) for p in sorted(run.glob("attempt_*.json"))]
    gates = [gate(d) for d in attempts]
    d_out = ex / slug
    d_out.mkdir(exist_ok=True)
    (d_out / "patch.diff").write_text((run / "patch.diff").read_text())
    md = [f"# {slug}", "", f"Result file `{fname}`, case `{case}`, run {n}.", ""]
    for d, g in zip(attempts, gates):
        md.append(f"## Attempt {d['attempt']}: {g}")
        md.append(f"Model diagnosis: {short(d.get('diagnosis') or d.get('error') or '(none)', 400)}")
        if d.get("tool_calls") is not None:
            md.append(f"Tool calls: {d['tool_calls']}; conversation stop: {d.get('turn_stop')}; submitted from: {d.get('submitted_from')}")
        dv = d.get("differential") or {}
        if g == "rejected at differential" and dv.get("examples"):
            e = dv["examples"][0]
            md.append(f"Counterexample returned to the model: input {short(e.get('probe'), 240)}; expected {short(e.get('expected'), 240)}; got {short(e.get('got'), 240)} ({e.get('where')})")
        md.append("")
    (d_out / "attempts.md").write_text("\n".join(md))
    sc = r.get("scored") or {}
    meta = {"folder": slug, "result_file": fname, "run_number": n, "case": case, "model": row.get("model"), "effort": row.get("effort"),
            "mode": mode(row), "layer": layer(row), "gate": gate_setting(row), "attempts": r.get("attempts"), "tokens_used": r.get("tokens_used"),
            "gate_per_attempt": gates, "rescored_verdict": sc.get("verdict"), "rescored_seed": sc.get("seed"),
            "submitted_from": attempts[-1].get("submitted_from")}
    (d_out / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    index.append(f"| [{slug}]({slug}/) | {case} | {row.get('model')} | {mode(row)} | {layer(row)} | {r.get('attempts')} | {r.get('tokens_used')} | "
                 f"{' -> '.join(gates)} | {sc.get('verdict', '-')} |")
(ex / "README.md").write_text("\n".join(index) + "\n")
print("\n".join(index))
print("\nwrote docs/RESULTS.md and", len(PICKS), "example folders")
